import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { promises as fs } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { openRoot } from '../../src/main/projectAccess.js';
import { applyPlanEdit, deletePlan, listPlans, planEditDiff, planStages, previewPlanEdit, savePlan, validPlanName } from '../../src/main/plans.js';

const GRID = (stages) =>
  `<!-- BEGIN aidlc composed-scope-grid: generated by \`aidlc engine graph compile\` -->\n\n\`\`\`json\n${JSON.stringify({ stages }, null, 2)}\n\`\`\`\n\n<!-- END aidlc composed-scope-grid -->\n`;

// The shape of aidlc/scopes/ultra-express.md in this repo, trimmed.
const DEMO = `---
name: demo
depth: Minimal
keywords: []
description: Plan saved from 261113-demo, based on bugfix
skeleton: off
review_cap: none
guard_policy: off
sensors: off
learnings: off
summary_confirmation: off
plan_approval: on
collaborators: off
---

# demo scope

${GRID({ 'state-init': 'EXECUTE', 'intent-capture': 'SKIP', 'code-generation': 'EXECUTE', 'build-and-test': 'EXECUTE' })}`;

// The shape of .claude/scopes/aidlc-bugfix.md: no grid block, the stages are in the compiled scope grid.
const BUGFIX = `---
name: bugfix
depth: Minimal
keywords:
  - fix
  - bug
description: Fix a specific bug
review_cap: advisory
sensors: on
plan_approval: on
---

# bugfix scope
`;

const SCOPE_GRID = { bugfix: { stages: { 'reverse-engineering': 'EXECUTE', 'market-research': 'SKIP' } } };

function fakeExec() {
  const calls = [];
  const exec = vi.fn(async (file, args) => {
    if (file !== 'aidlc') return '__AIDLC_DASH_PATH__/usr/bin';
    calls.push(args);
    return 'done\n';
  });
  return { exec, calls };
}

let tmp;
let root;
const write = async (rel, text) => {
  await fs.mkdir(path.dirname(path.join(tmp, rel)), { recursive: true });
  await fs.writeFile(path.join(tmp, rel), text);
};
const there = (rel) =>
  fs.stat(path.join(root, rel)).then(
    () => true,
    () => false
  );

beforeEach(async () => {
  tmp = await fs.mkdtemp(path.join(os.tmpdir(), 'plans-'));
  await write('aidlc/scopes/demo.md', DEMO);
  await write('.claude/scopes/aidlc-demo.md', DEMO.split('<!-- BEGIN')[0]);
  await write('.aidlc/scopes/aidlc-demo.md', DEMO.split('<!-- BEGIN')[0]);
  await write('.claude/scopes/aidlc-bugfix.md', BUGFIX);
  await write('.claude/tools/data/scope-grid.json', JSON.stringify(SCOPE_GRID));
  root = await openRoot(tmp);
});
afterEach(() => fs.rm(tmp, { recursive: true, force: true }));

const running = { dirName: '261114-x', slug: 'x', scope: 'demo', status: 'in-flight', executed: 5, done: 2 };
const finished = { dirName: '261113-y', slug: 'y', scope: 'demo', status: 'complete' };

describe('plans (EPIC-09 US-0903)', () => {
  it('lists every plan with depth, stage count, defaults and the intents on it', async () => {
    const plans = await listPlans(root, 'claude', 'demo', [running, finished]);
    expect(plans.map((p) => p.name)).toEqual(['demo', 'bugfix']);
    const [demo, bugfix] = plans;
    expect(demo).toMatchObject({ own: true, active: true, depth: 'Minimal', stageCount: 3, description: 'Plan saved from 261113-demo, based on bugfix' });
    expect(demo.defaults).toEqual({
      review_cap: 'none',
      sensors: 'off',
      learnings: 'off',
      summary_confirmation: 'off',
      plan_approval: 'on',
      guard_policy: 'off',
      collaborators: 'off'
    });
    expect(demo.intents).toEqual([
      { dirName: '261114-x', slug: 'x', running: true },
      { dirName: '261113-y', slug: 'y', running: false }
    ]);
    expect(bugfix).toMatchObject({ own: false, active: false, stageCount: 1, defaults: { review_cap: 'advisory', learnings: null } });
  });

  it('splits stages into EXECUTE and SKIP, from the grid block or the compiled grid for stock plans', async () => {
    expect(await planStages(root, 'claude', 'demo')).toEqual({ execute: ['state-init', 'code-generation', 'build-and-test'], skip: ['intent-capture'] });
    expect(await planStages(root, 'claude', 'bugfix')).toEqual({ execute: ['reverse-engineering'], skip: ['market-research'] });
    await expect(planStages(root, 'claude', 'nope')).rejects.toThrow(/nope/);
  });

  it('allows only lowercase words joined by hyphens as a plan name', async () => {
    expect(validPlanName('my-plan-2')).toBe(true);
    for (const bad of ['Bad Name', '../x', 'a/b', '-x', 'x-', 'a--b', '', 'Ä', null]) expect(validPlanName(bad), String(bad)).toBe(false);
    await expect(planStages(root, 'claude', '../x')).rejects.toThrow();
  });

  it('saves the running plan with fixed arguments, and refuses an invalid name before running', async () => {
    const { exec, calls } = fakeExec();
    expect(await savePlan(root, 'my-plan', { exec })).toEqual({ ok: true, command: 'aidlc engine scope save --name my-plan', output: 'done' });
    expect(calls).toEqual([['engine', 'scope', 'save', '--name', 'my-plan']]);
    await expect(savePlan(root, 'Bad Name', { exec })).rejects.toThrow(/Bad Name/);
    expect(calls).toHaveLength(1);
  });

  it('edits only the frontmatter fields given, above the grid marker', () => {
    const { next, diff } = planEditDiff(BUGFIX, { description: 'Fix one bug: fast', depth: 'Standard', keywords: ['fix', 'bug', 'hotfix'] });
    expect(diff.split('\n')).toEqual([
      '- description: Fix a specific bug',
      '- depth: Minimal',
      '- keywords:',
      '-   - fix',
      '-   - bug',
      '+ description: "Fix one bug: fast"',
      '+ depth: Standard',
      '+ keywords: [fix, bug, hotfix]'
    ]);
    expect(next).toContain('depth: Standard\nkeywords: [fix, bug, hotfix]\ndescription: "Fix one bug: fast"\nreview_cap: advisory');
    expect(next.split('---\n').slice(2).join('---\n')).toBe(BUGFIX.split('---\n').slice(2).join('---\n')); // body untouched
    const demo = planEditDiff(DEMO, { depth: 'Comprehensive' });
    expect(demo.diff).toBe('- depth: Minimal\n+ depth: Comprehensive');
    expect(demo.next).toBe(DEMO.replace('depth: Minimal', 'depth: Comprehensive')); // the grid is untouched
    expect(() => planEditDiff(DEMO, { depth: 'Huge' })).toThrow();
    expect(() => planEditDiff(DEMO, { description: 'two\nlines' })).toThrow();
    expect(() => planEditDiff(DEMO, { keywords: ['ok', 'no]'] })).toThrow();
  });

  it('applies an edit, removes the harness copies and recompiles; refuses a stock plan and a changed file', async () => {
    const { exec, calls } = fakeExec();
    const { before, diff } = await previewPlanEdit(root, 'demo', { description: 'Short work' });
    expect(diff).toBe('- description: Plan saved from 261113-demo, based on bugfix\n+ description: Short work');
    const res = await applyPlanEdit(root, 'demo', { description: 'Short work' }, before, { exec });
    expect(res).toMatchObject({ ok: true, file: 'aidlc/scopes/demo.md', command: 'aidlc engine graph compile' });
    expect(calls).toEqual([['engine', 'graph', 'compile']]);
    expect(await fs.readFile(path.join(root, 'aidlc/scopes/demo.md'), 'utf8')).toBe(DEMO.replace(/^description: .*$/m, 'description: Short work'));
    expect(await there('.claude/scopes/aidlc-demo.md')).toBe(false);
    expect(await there('.aidlc/scopes/aidlc-demo.md')).toBe(false);

    await expect(previewPlanEdit(root, 'bugfix', { depth: 'Standard' })).rejects.toThrow(/bugfix/);
    await expect(applyPlanEdit(root, 'bugfix', { depth: 'Standard' }, BUGFIX, { exec })).rejects.toThrow(/bugfix/);
    await expect(applyPlanEdit(root, 'demo', { depth: 'Standard' }, before, { exec })).rejects.toThrow(/aidlc\/scopes\/demo\.md/);
    expect(calls).toHaveLength(1);
  });

  it('refuses to delete a plan an intent in progress uses; otherwise removes both files and recompiles', async () => {
    const { exec, calls } = fakeExec();
    await expect(deletePlan(root, 'demo', [running], { exec })).rejects.toThrow(/x/);
    await expect(deletePlan(root, 'bugfix', [], { exec })).rejects.toThrow(/bugfix/);
    expect(await there('aidlc/scopes/demo.md')).toBe(true);
    expect(calls).toEqual([]);

    expect(await deletePlan(root, 'demo', [finished], { exec })).toMatchObject({ ok: true });
    expect(await there('aidlc/scopes/demo.md')).toBe(false);
    expect(await there('.claude/scopes/aidlc-demo.md')).toBe(false);
    expect(await there('.claude/scopes/aidlc-bugfix.md')).toBe(true);
    expect(calls).toEqual([['engine', 'graph', 'compile']]);
  });
});
